const { chromium } = require('playwright');
/* End-to-end check of the own-yard flow: new design, house, trace image and scale, wishes, export, My designs.
 *   node scripts/e2e_custom.js [output-dir] */
const path = require('path'), fs = require('fs');
const D = (process.argv[2] || path.resolve(__dirname, '../test-output')) + '/';
fs.mkdirSync(D, { recursive: true });
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 }, offline: true, acceptDownloads: true });
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  const ok = (c, m) => { if (!c) process.exitCode = 1; console.log((c ? '[yard] ok: ' : '[yard] FAIL: ') + m); };
  await p.goto('file://' + path.resolve(__dirname, '../dist/verdant-studio.html') + ''); await p.waitForTimeout(500);
  const scr = (x, y) => p.evaluate(([x, y]) => { const s = document.getElementById('plan'), r = s.getBoundingClientRect(), vb = s.getAttribute('viewBox').split(' ').map(Number); return [r.left + (x - vb[0]) / vb[2] * r.width, r.top + (y - vb[1]) / vb[3] * r.height]; }, [x, y]);
  const st = () => p.evaluate(() => JSON.parse(localStorage.getItem('scottDesign.v1')));
  await p.click('[data-tool="dtree"]'); let [x, y] = await scr(20, 24); await p.mouse.click(x, y); await p.keyboard.press('Escape');
  const scottPid = (await st()).pid;
  await p.click('#bNew'); await p.click('[data-new="custom"]');
  await p.fill('#nfName', 'Garcia Backyard'); await p.fill('#nfClient', 'Maria Garcia');
  await p.fill('#nfW', '60'); await p.fill('#nfH', '100'); await p.click('[data-nq="90"]'); await p.fill('#nfStreetName', 'Oak Street');
  const png = await p.evaluate(() => { const c = document.createElement('canvas'); c.width = 900; c.height = 1200; const g = c.getContext('2d');
    g.fillStyle = '#78965F'; g.fillRect(0, 0, 900, 1200); g.strokeStyle = '#eee'; g.lineWidth = 6; g.strokeRect(150, 250, 600, 800); g.strokeStyle = 'red'; g.lineWidth = 8;
    g.beginPath(); g.moveTo(150, 1100); g.lineTo(750, 1100); g.stroke(); return c.toDataURL('image/png').split(',')[1]; });
  await p.setInputFiles('#nfImg', { name: 'yard.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await p.click('#nfCreate'); await p.waitForTimeout(900);
  let s = await st();
  ok(s.site && s.site.w === 60 && s.items[0].type === 'building', 'own-yard design created with a house');
  ok(s.site.north === 90, 'New design: the Right button sets north to 90°');
  ok(s.site.img && s.site.img.w === 60, 'trace image imported');
  ok(/Garcia Backyard/.test(await p.textContent('header h1')), 'header shows project name');
  await p.click('#goScale');
  const im = s.site.img;
  [x, y] = await scr(im.x + im.w * 150 / 900, im.y + im.h * 1100 / 1200); const [x2, y2] = await scr(im.x + im.w * 750 / 900, im.y + im.h * 1100 / 1200);
  await p.mouse.move(x, y); await p.mouse.down(); await p.mouse.move(x2, y2, { steps: 6 }); await p.mouse.up();
  await p.fill('#scaleLen', '50'); await p.click('#scaleOk'); await p.waitForTimeout(300);
  s = await st();
  ok(Math.abs(s.site.img.w - 75) < 1.5, 'image scaled so the red line is 50 ft (width ' + s.site.img.w + ')');
  await p.click('[data-tool="dtree"]'); [x, y] = await scr(15, 20); await p.mouse.click(x, y); await p.keyboard.press('Escape');
  await p.click('[data-tool="patio"]'); [x, y] = await scr(40, 50); await p.mouse.click(x, y);
  await p.click('[data-pane="pWants"]'); await p.fill('#wantNew', 'Shade on the patio'); await p.click('#wantAdd');
  s = await st();
  ok(s.wants.length === 1, 'custom client wish added');
  await p.click('[data-pane="pCheck"]'); await p.click('#bCheck');
  ok(/Shade on the patio/.test(await p.textContent('#issues')), 'check lists the custom wish');
  await p.keyboard.press('Escape'); await p.click('#zFit');
  await p.screenshot({ path: D + 'out/custom-ui.png' });
  await p.click('#bExport'); await p.waitForTimeout(400);
  const scaleTxt = await p.textContent('#dlgBody');
  ok(/1 in = \d+ ft/.test(scaleTxt), 'export uses ' + (scaleTxt.match(/1 in = \d+ ft/) || [''])[0]);
  ok(await p.inputValue('[data-title="project"]') === 'Garcia Backyard' && await p.inputValue('[data-title="client"]') === 'Maria Garcia', 'title block form starts from the project details');
  ok(!(await p.$('[data-title="section"]')), 'own-yard title block has no lab section');
  await p.fill('[data-title="designer"]', '');
  await p.click('[data-fmt="png"]'); await p.waitForTimeout(300);
  ok(/Fill in the designer/.test(await p.textContent('#dlgBody')) && await p.getAttribute('[data-title="designer"]', 'aria-invalid') === 'true', 'export asks for the missing designer');
  await p.fill('[data-title="designer"]', 'Pat Student'); await p.fill('[data-title="address"]', '1204 Oak St., Russellville, AR');
  await p.fill('[data-title="company"]', 'Green Leaf Landscapes'); await p.fill('[data-title="contact"]', 'pat@example.com');
  await p.waitForTimeout(500);
  const sheet = await p.evaluate(() => decodeURIComponent(document.getElementById('exPreview').src.split(',').slice(1).join(',')));
  const words = (sheet.match(/>[^<>]+</g) || []).join(' ');
  ok(!/SCOTT|Scott|AGPS|ARKANSAS TECH|LAB SECTION/.test(words), 'own-yard sheet has nothing from the Scott lab');
  ok(/GARCIA BACKYARD/.test(words) && /MARIA GARCIA|Maria Garcia/.test(words) && /1204 Oak St/.test(words) && /GREEN LEAF LANDSCAPES/.test(words) && /Pat Student/.test(words) && /pat@example.com/.test(words), 'sheet shows the project, client, address, company, designer and contact typed in');
  await p.fill('#exNorth', '25'); await p.selectOption('#exArrow', 'rose'); await p.waitForTimeout(500);
  s = await st();
  ok(s.site.north === 25 && s.title.arrow === 'rose', 'export: any north angle and a compass-rose style');
  const sheet2 = await p.evaluate(() => decodeURIComponent(document.getElementById('exPreview').src.split(',').slice(1).join(',')));
  ok(/rotate\(25\)/.test(sheet2) && />N</.test(sheet2), 'sheet draws the rose rotated 25° with an N');
  await p.click('[data-nq="0"][data-for="exNorth"]'); await p.waitForTimeout(800);
  ok((await st()).site.north === 0, 'quick button sets north straight up');
  const [d] = await Promise.all([p.waitForEvent('download'), p.click('[data-fmt="png"]')]); await d.saveAs(D + 'out/custom-sheet.png');
  await p.keyboard.press('Escape');
  await p.click('[data-menu="0"]'); await p.click('[data-m="mine"]');
  await p.click(`[data-open="${scottPid}"]`); await p.waitForTimeout(500);
  s = await st();
  ok(!s.site && s.items.length === 1, 'switched back to the Scott design');
  await p.click('[data-menu="0"]'); await p.click('[data-m="mine"]');
  ok((await p.$$('[data-open]')).length === 1, 'My designs lists the other design');
  ok(errs.length === 0, 'no console errors ' + errs.join(' | ')); await b.close();
})();
